"""Generate /assets/i18n.js (the app's translation layer) and the French review file.

How it works (decided 9 Oct 2026, Session 51):
- The app pages (dashboard, login, signup, reset-password) stay single English files.
  i18n.js watches the page (MutationObserver) and swaps any text node, placeholder,
  aria-label or title whose whole text is a key in the dictionary for the visitor's
  language. Program logic never sees the translation: JS variables keep the English
  values (tier names in localStorage, 'running'/'stopped' states, saved labels).
- Text with numbers in it is matched by PATTERNS (anchored regexes).
- A text with no entry stays English: a changed English string loses its translation
  silently, so re-run the collector (see below) after copy changes.
- Language on app pages: ?lang= (consent.js adds lang=fr to sign-up/login links on
  French pages) > the visitor's own choice (switch or ?lang=, localStorage
  snypd_ui_lang, also saved to user_metadata.ui_lang) > browser language > English.
- Public pages keep their own language (html lang); consent.js loads this file on
  French pages so the cookie banner is French there.

Edit ops/i18n/fr.py (the strings) or this file (the runtime), then run from the repo root:

    python ops/i18n/gen_i18n.py

It writes assets/i18n.js (pure ASCII: every non-ASCII char is a \\u escape) and
C:/Users/Tanus/website/outreach/15-fr-ui-review.md when that folder exists.
Collector: open an app page with ?i18n_collect=1 and read window.SNYPD_I18N.missing()
for every visible English text that has no French yet.
ops/ is in .vercelignore, so this script never deploys.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from fr import FR, FR_PATTERNS  # noqa: E402

REVIEW = r'C:\Users\Tanus\website\outreach\15-fr-ui-review.md'

RUNTIME = r"""/* SNYPD app translation layer. GENERATED by ops/i18n/gen_i18n.py - do not edit by hand.
 * Swaps whole English texts for the visitor's language as they appear in the page.
 * Pure ASCII on purpose (non-ASCII characters are \u escapes).
 */
(function () {
  'use strict';
  if (window.SNYPD_I18N) return;
  var DICT = __DICT__;
  var PATTERNS = __PATTERNS__;
  var SUPPORTED = ['en'].concat(Object.keys(DICT));
  var html = document.documentElement;
  var isApp = html.hasAttribute('data-i18n-app');
  var qs = new URLSearchParams(location.search);
  var collect = qs.get('i18n_collect') === '1';

  function get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function put(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  function ok(l) { return !!l && SUPPORTED.indexOf(l) !== -1; }

  function pick() {
    if (!isApp) return (html.getAttribute('lang') || 'en').slice(0, 2).toLowerCase();
    var q = (qs.get('lang') || '').toLowerCase();
    if (ok(q)) { put('snypd_ui_lang', q); return q; }
    var s = get('snypd_ui_lang'); if (ok(s)) return s;
    var navs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
    var first = String(navs[0] || '').slice(0, 2).toLowerCase();
    return ok(first) ? first : 'en';
  }

  var lang = pick();
  var D = DICT[lang] || null;
  var P = (PATTERNS[lang] || []).map(function (p) { return [new RegExp(p[0]), p[1]]; });
  var missing = {};
  if (isApp && D) html.setAttribute('lang', lang);

  /* "\u20ac62.50" -> "62,50 \u20ac" (French order and decimal comma), anywhere in a text. */
  var MONEY = /([\u20ac\u00a3$])\s?(\d{1,3}(?:,\d{3})+|\d+)(?:\.(\d{1,2}))?(?![\d.,]*\d)/g;
  /* A bare count like "5,399" (its own text node, e.g. inside <b>) -> "5 399". */
  var COUNT = /^\d{1,3}(?:,\d{3})+$/;
  function money(s) {
    if (lang !== 'fr') return s;
    if (COUNT.test(s)) return s.replace(/,/g, '\u202f');
    return s.replace(MONEY, function (all, sym, whole, dec) {
      return whole.replace(/,/g, '\u202f') + (dec ? ',' + (dec.length === 1 ? dec + '0' : dec) : '') + '\u00a0' + sym;
    });
  }
  var VALUES = {};
  if (D) for (var vk in D) if (Object.prototype.hasOwnProperty.call(D, vk)) VALUES[D[vk]] = 1;

  function tr(text) {
    if (!D || text == null) return null;
    var k = String(text).replace(/\s+/g, ' ').trim();
    if (!k || VALUES[k]) return null;
    var out = Object.prototype.hasOwnProperty.call(D, k) ? D[k] : null;
    if (out == null) {
      /* Patterns run in order and each sees the previous one's result, so a line can
         be translated part by part ("Nike \u2022 Promoted \u2022 Seen 5m ago"). */
      var s = k;
      for (var i = 0; i < P.length; i++) s = s.replace(P[i][0], P[i][1]);
      if (s !== k) out = s;
    }
    if (out == null) {
      var mo = money(k);
      if (mo !== k) out = mo;
    } else {
      out = money(out);
    }
    if (out == null) { if (collect && /[A-Za-z]{2}/.test(k)) missing[k] = (missing[k] || 0) + 1; return null; }
    var lead = /^\s*/.exec(text)[0], trail = /\s*$/.exec(text)[0];
    return lead + out + trail;
  }

  var SKIP_TAG = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, NOSCRIPT: 1, CODE: 1 };
  var SKIP_SEL = '[data-i18n-skip]';
  function skipped(el) { return !el || SKIP_TAG[el.nodeName] || (el.closest && el.closest(SKIP_SEL)); }
  var ATTRS = ['placeholder', 'aria-label', 'title'];

  function attrs(el) {
    for (var i = 0; i < ATTRS.length; i++) {
      var v = el.getAttribute(ATTRS[i]);
      if (v) { var t = tr(v); if (t != null && t !== v) el.setAttribute(ATTRS[i], t); }
    }
    if (el.nodeName === 'INPUT' && /^(button|submit)$/i.test(el.type) && el.value) {
      var tv = tr(el.value); if (tv != null && tv !== el.value) el.value = tv;
    }
  }

  function walk(n) {
    if (n.nodeType === 3) {
      if (skipped(n.parentNode)) return;
      var t = tr(n.nodeValue);
      if (t != null && t !== n.nodeValue) n.nodeValue = t;
    } else if (n.nodeType === 1) {
      if (skipped(n)) return;
      attrs(n);
      for (var c = n.firstChild; c; c = c.nextSibling) walk(c);
    }
  }

  var styled = false;
  function switcher(el) {
    if (!el || el.getAttribute('data-i18n-ready')) return;
    if (!styled) {
      styled = true;
      var st = document.createElement('style');
      st.textContent = '[data-i18n-switch]{display:inline-flex;gap:6px}' +
        '.i18n-sw{font:inherit;font-size:12px;letter-spacing:.08em;padding:4px 10px;background:transparent;color:inherit;border:1px solid rgba(255,255,255,.25);border-radius:4px;cursor:pointer;opacity:.7}' +
        '.i18n-sw.is-on{opacity:1;border-color:#00E5A0;color:#00E5A0}';
      document.head.appendChild(st);
    }
    el.setAttribute('data-i18n-ready', '1');
    el.setAttribute('data-i18n-skip', '');
    var langs = SUPPORTED, names = { en: 'EN', fr: 'FR' };
    el.innerHTML = langs.map(function (l) {
      return '<button type="button" data-l="' + l + '" aria-pressed="' + (l === lang) + '" class="i18n-sw' + (l === lang ? ' is-on' : '') + '">' + (names[l] || l.toUpperCase()) + '</button>';
    }).join('');
    el.addEventListener('click', function (e) {
      var b = e.target.closest && e.target.closest('button[data-l]');
      if (b) api.set(b.getAttribute('data-l'));
    });
  }

  var api = window.SNYPD_I18N = {
    lang: lang,
    t: function (s) { var r = tr(s); return r == null ? s : r; },
    set: function (l) {
      if (!ok(l)) return;
      put('snypd_ui_lang', l);
      var done = function () {
        var u = new URL(location.href); u.searchParams.delete('lang'); location.replace(u.toString());
      };
      try {
        if (api.onChange) { Promise.resolve(api.onChange(l)).then(done, done); return; }
      } catch (e) {}
      done();
    },
    /* Called by a page once it has the signed-in user: a language saved on the
       account wins over the browser's when this device has no explicit choice. */
    fromUser: function (user) {
      var l = user && user.user_metadata && user.user_metadata.ui_lang;
      if (ok(l) && !get('snypd_ui_lang') && l !== lang) { put('snypd_ui_lang', l); location.reload(); }
    },
    missing: function () { return Object.keys(missing).sort(); },
    onChange: null
  };

  if (!D) {
    if (isApp) document.addEventListener('DOMContentLoaded', function () {
      var sw = document.querySelectorAll('[data-i18n-switch]'); for (var i = 0; i < sw.length; i++) switcher(sw[i]);
    });
    return;
  }

  var origConfirm = window.confirm;
  window.confirm = function (m) { return origConfirm.call(window, api.t(m)); };
  var origAlert = window.alert;
  window.alert = function (m) { return origAlert.call(window, api.t(m)); };

  new MutationObserver(function (list) {
    for (var i = 0; i < list.length; i++) {
      var m = list[i];
      if (m.type === 'childList') { for (var j = 0; j < m.addedNodes.length; j++) walk(m.addedNodes[j]); }
      else if (m.type === 'characterData') walk(m.target);
      else if (m.type === 'attributes' && !skipped(m.target)) attrs(m.target);
    }
  }).observe(html, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS.concat(['value']) });

  function start() {
    walk(document.documentElement);
    var sw = document.querySelectorAll('[data-i18n-switch]'); for (var i = 0; i < sw.length; i++) switcher(sw[i]);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
"""


def ascii_json(obj):
    return json.dumps(obj, ensure_ascii=True, separators=(',', ':'), sort_keys=True)


def build():
    for k, v in FR.items():
        if k != ' '.join(k.split()):
            sys.exit('key has extra whitespace: %r' % k)
        if not v.strip():
            sys.exit('empty translation for %r' % k)
    js = RUNTIME.replace('__DICT__', ascii_json({'fr': FR})).replace('__PATTERNS__', ascii_json({'fr': FR_PATTERNS}))
    js.encode('ascii')  # raises if anything slipped through
    with open(os.path.join(ROOT, 'assets', 'i18n.js'), 'w', encoding='ascii', newline='\n') as fh:
        fh.write(js)
    print('wrote assets/i18n.js', len(js), 'bytes,', len(FR), 'strings,', len(FR_PATTERNS), 'patterns')
    if os.path.isdir(os.path.dirname(REVIEW)):
        rows = ['# French app text (sign-up, login, dashboard, history, Market Insights, /plans, /account)', '',
                'Generated by `ops/i18n/gen_i18n.py` from `ops/i18n/fr.py`. Read the right-hand column like a French',
                'reseller would. Reply with the line numbers to change (or "ok") and it goes live.', '',
                '| # | English (on screen today) | French |', '|---|---|---|']
        for i, (k, v) in enumerate(FR.items(), 1):
            rows.append('| %d | %s | %s |' % (i, k.replace('|', '\\|'), v.replace('|', '\\|')))
        rows += ['', '## Texts with numbers', '', '| Pattern (English) | French |', '|---|---|']
        for src, rep in FR_PATTERNS:
            rows.append('| `%s` | `%s` |' % (src.replace('|', '\\|'), rep.replace('|', '\\|')))
        with open(REVIEW, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write('\n'.join(rows) + '\n')
        print('wrote', REVIEW)


if __name__ == '__main__':
    build()
