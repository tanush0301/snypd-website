// node ops/i18n/gen_stock_i18n.cjs  ->  writes assets/stock-i18n.js (pure ASCII: every non-ASCII character becomes a unicode escape).
// Fails (exit 1) if EN and FR keys differ, a placeholder differs, or a French string equals its English one where that is not expected.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { en, fr } = require('./stock_strings.cjs');

const problems = [];
const same = new Set(['tab', 'title', 'plat.vinted', 'plat.ebay', 'plat.depop', 'plat.vestiaire', 'plat.marktplaats', 'plat.facebook', 'h.at', 'detail.cost', 'f.source', 'f.notes', 'f.date', 'h.via']);
const ph = s => (s.match(/\{[a-z]+\}/g) || []).sort().join(',');
for (const k of Object.keys(en)) {
  if (!(k in fr)) { problems.push('missing French: ' + k); continue; }
  if (ph(en[k]) !== ph(fr[k])) problems.push('placeholder mismatch: ' + k);
  if (en[k] === fr[k] && !same.has(k) && /[a-z]{4}/i.test(en[k])) problems.push('French equals English: ' + k + ' = ' + en[k]);
}
for (const k of Object.keys(fr)) if (!(k in en)) problems.push('extra French key: ' + k);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const esc = s => s.replace(/[^\x20-\x7e]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const body = JSON.stringify({ en, fr }, null, 1).split('\n').map(esc).join('\n');
const out = '/* GENERATED by ops/i18n/gen_stock_i18n.cjs from ops/i18n/stock_strings.cjs. Do not edit. Pure ASCII. */\nwindow.SNYPD_STOCK_STR = ' + body + ';\n';
fs.writeFileSync(path.join(__dirname, '..', '..', 'assets', 'stock-i18n.js'), out);
console.log(`assets/stock-i18n.js: ${Object.keys(en).length} keys x 2 languages, ${out.length} bytes, non-ASCII bytes: ${(out.match(/[^\x20-\x7e\n]/g) || []).length}`);
